#!/usr/bin/env node
// Writes the files generated from skills/: the Claude Code plugin marketplace
// and the skills table in README.md. With --check, fails instead of writing
// when either is out of date (CI runs that). Run: npm run build

import { readFileSync, writeFileSync } from 'node:fs';
import { basename, join } from 'node:path';

import { loadSkills, PACKAGE_ROOT, summary } from '../src/skills.mjs';

const checkOnly = process.argv.includes('--check');
const skills = loadSkills();
const pkg = JSON.parse(readFileSync(join(PACKAGE_ROOT, 'package.json'), 'utf8'));

// One plugin per skill, so people install only the ones they want. The entry
// is the plugin's manifest ("strict": false), as anthropics/skills does it.
const marketplace = {
  name: 'agentrail-skills',
  owner: { name: 'Agentrail' },
  metadata: {
    description: "Agentrail's Agent Skills: set up Agentrail and get more from it.",
    version: pkg.version,
  },
  plugins: skills.map((skill) => ({
    name: skill.name,
    source: './',
    strict: false,
    description: summary(skill.description, 300),
    version: skill.version,
    license: 'Apache-2.0',
    skills: [`./skills/${basename(skill.dir)}`],
  })),
};

const START = '<!-- skills-table:start (generated by npm run build) -->';
const END = '<!-- skills-table:end -->';
const table = [
  START,
  '',
  '| Skill | What it does | Version |',
  '| ----- | ------------ | ------- |',
  ...skills.map(
    (skill) =>
      `| [\`${skill.name}\`](skills/${basename(skill.dir)}/SKILL.md)${skill.recommended ? ' **Start here**' : ''} | ${summary(skill.description, 220)} | ${skill.version} |`,
  ),
  '',
  END,
].join('\n');

const outputs = new Map();
outputs.set(join(PACKAGE_ROOT, '.claude-plugin', 'marketplace.json'), `${JSON.stringify(marketplace, null, 2)}\n`);

const readmePath = join(PACKAGE_ROOT, 'README.md');
const readme = readFileSync(readmePath, 'utf8');
const startAt = readme.indexOf(START);
const endAt = readme.indexOf(END);
if (startAt === -1 || endAt === -1) throw new Error(`README.md must contain ${START} and ${END}`);
outputs.set(readmePath, readme.slice(0, startAt) + table + readme.slice(endAt + END.length));

let stale = 0;
for (const [path, content] of outputs) {
  let current = null;
  try {
    current = readFileSync(path, 'utf8');
  } catch (error) {
    if (error.code !== 'ENOENT') throw error;
  }
  if (current === content) continue;
  if (checkOnly) {
    stale += 1;
    process.stderr.write(`${path} is out of date. Run npm run build.\n`);
  } else {
    writeFileSync(path, content);
    process.stdout.write(`wrote ${path}\n`);
  }
}
if (stale > 0) process.exit(1);
